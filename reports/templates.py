TEXT_TEMPLATE = """=== Phantom Optimizer Report ===
Generated: {timestamp}

--- System Information ---
{system_info}

--- Live Monitor ---
{live_monitor}

--- Recent Logs ---
{logs_text}

--- Summary ---
Version: {version}
Year: {year}
"""


# ===============================
# Helper: Rendering
# ===============================

def render_html_report(system_info: str, live_monitor: dict, logs: list, version="1.5") -> str:
    """
    Renders the HTML template with the given data.
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    live_html = "".join([f"<li><b>{k}:</b> {v}</li>" for k, v in (live_monitor or {}).items()])
    logs_rows = "".join([
        f"<tr><td>{c}</td><td>{t}</td><td>{s}</td><td>{m}</td></tr>"
        for (c, t, s, m) in (logs or [])
    ])

    return HTML_TEMPLATE.format(
        timestamp=timestamp,
        system_info=system_info.strip(),
        live_monitor=live_html,
        logs_rows=logs_rows,
        version=version,
        year=datetime.now().year
    )


def render_text_report(system_info: str, live_monitor: dict, logs: list, version="1.5") -> str:
    """
    Renders a plain text report (TXT export).
    """
    timestamp = datetime.now().strftime("%Y-%m-%d %H:%M:%S")

    live_text = "\n".join([f"{k}: {v}" for k, v in (live_monitor or {}).items()])
    logs_text = "\n".join([" | ".join(map(str, e)) for e in (logs or [])])

    return TEXT_TEMPLATE.format(
        timestamp=timestamp,
        system_info=system_info.strip(),
        live_monitor=live_text,
        logs_text=logs_text,
        version=version,
        year=datetime.now().year
    )